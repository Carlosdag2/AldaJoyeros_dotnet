  `fecha_entrega_real` date DEFAULT NULL,
  `direccion_id` bigint DEFAULT NULL,
  `usuario_id` bigint DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `UK2lh8uqayatwwopmwye4sdpp66` (`direccion_id`),
  KEY `FK6uxomgomm93vg965o8brugt00` (`usuario_id`),
